function patch(rows: string[], p: string, x0: number, y0: number): void {
  p.split(' ').forEach((line, dy) => {
    const y = y0 + dy;
    const row = rows[y].split('');
    for (let dx = 0; dx < line.length; dx++) if (line[dx] !== '.') row[x0 + dx] = line[dx];
    rows[y] = row.join('');
  });
}

function emotionDef(e: EmotionId): Def {
  const spec = EMO[e] ?? EMO.neutral;
  const rows = FACE.slice();
  patch(rows, EYES[spec.eyes], 3, 3);
  patch(rows, MOUTH[spec.mouth], 4, 9);
  return { a: spec.face, c: spec.c ?? V.coral, rows };
}

// ── Rendering ──

const COLOR_OF: Record<string, (d: Def) => string> = {
  '#': () => 'var(--cth-ink-900)',
  a: (d) => d.a,
  c: (d) => d.c ?? d.a,
  w: () => 'var(--cth-cream-50)',
  g: () => 'var(--cth-ink-500)',
  l: () => 'var(--cth-ink-300)'
};

interface Built { fills: { color: string; d: string }[] }
const cache = new Map<string, Built>();

function build(name: string, def: Def): Built {
  const hit = cache.get(name);
  if (hit) return hit;
  const byChar = new Map<string, string>();
  def.rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let run = 1;
      while (x + run < row.length && row[x + run] === ch) run++;
      if (ch !== '.' && COLOR_OF[ch]) byChar.set(ch, (byChar.get(ch) ?? '') + `M${x} ${y}h${run}v1h-${run}z`);
      x += run;
    }
  });
  // Draw fills first and ink last so the outline always sits on top.
  const order = ['w', 'l', 'g', 'a', 'c', '#'];
  const built: Built = {
    fills: order.filter((ch) => byChar.has(ch)).map((ch) => ({ color: COLOR_OF[ch](def), d: byChar.get(ch)! }))
  };
  cache.set(name, built);
  return built;
}

function defFor(name: string): Def | null {
  if (name.startsWith('emo-')) return emotionDef(name.slice(4) as EmotionId);
  return (DEFS as Record<string, Def>)[name] ?? null;
}

export interface GIconProps {
  name: GIconName | string;
  /** Pixel size; keep it a multiple of 16 for crisp pixels. */
  px?: number;
  style?: CSSProperties;
  title?: string;
}

const BASE_NAMES: readonly BaseIconName[] = [
  'gear', 'plus', 'x', 'check', 'arrow-right', 'pause', 'play', 'bell', 'folder', 'terminal', 'code', 'web', 'mcp', 'sparkle', 'expand', 'minimize'
];

export const GIcon = memo(function GIcon({ name, px = 16, style, title }: GIconProps) {
  const def = defFor(name);
  if (!def) {
    // Fall back to the original icon set (gear, x, check, plus ...).
    // An id nobody drew (from a goal, a feed line, a future power) must never take the interface down: show a sparkle.
    const base = (BASE_NAMES as readonly string[]).includes(name) ? (name as BaseIconName) : 'sparkle';
    return <BaseIcon name={base} size={Math.max(1, Math.round(px / 16))} style={style} />;
  }
  const b = build(name, def);
  return (
    <svg viewBox="0 0 16 16" width={px} height={px} shapeRendering="crispEdges"
      style={{ display: 'block', flexShrink: 0, ...style }} aria-hidden={title ? undefined : true}>
      {title && <title>{title}</title>}
      {b.fills.map((f, i) => <path key={i} d={f.d} fill={f.color} />)}
    </svg>
  );
});

